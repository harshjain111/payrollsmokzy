#!/usr/bin/env node
// Bundles supabase/migrations/*.sql into the migrate-to-new-project edge function so it can
// create the schema on the new project without the Supabase CLI. Re-run after adding migrations:
//   node scripts/migrate-supabase/bundle-migrations.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const dir = join(root, 'supabase', 'migrations');
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const entries = files.map((f) => {
  const base = f.replace(/\.sql$/, '');
  const i = base.indexOf('_');
  return { version: i === -1 ? base : base.slice(0, i), name: i === -1 ? '' : base.slice(i + 1), sql: readFileSync(join(dir, f), 'utf8') };
});
const out =
  '// GENERATED by scripts/migrate-supabase/bundle-migrations.mjs. Do not edit by hand.\n' +
  '// Every file in supabase/migrations, in order, so the schema can be applied to the new project.\n' +
  'export const MIGRATIONS: { version: string; name: string; sql: string }[] = ' +
  JSON.stringify(entries, null, 1) + ';\n';
const target = join(root, 'supabase', 'functions', 'migrate-to-new-project', 'migrations.ts');
writeFileSync(target, out);
console.log(`Bundled ${entries.length} migrations into ${target}`);
